/* --------------------------------------------------------------------------
   Motor de traducción
   -------------------------------------------------------------------------- */
(function () {
  const STORAGE_KEY = "latrama.lang";
  const FALLBACK = "es";
  let current = FALLBACK;

  const getDict = (lang) => I18N[lang] || I18N[FALLBACK];

  function detectLang() {
    const url = new URLSearchParams(window.location.search).get("lang");
    if (url && I18N[url]) return url;
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && I18N[saved]) return saved;
    } catch (e) { /* almacenamiento no disponible */ }
    return FALLBACK;
  }

  function t(key) {
    const dict = getDict(current);
    return dict[key] !== undefined ? dict[key] : (I18N[FALLBACK][key] !== undefined ? I18N[FALLBACK][key] : key);
  }

  function applyLang(lang) {
    if (!I18N[lang]) lang = FALLBACK;
    current = lang;
    const dict = getDict(lang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (dict[key] !== undefined) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const key = el.getAttribute("data-i18n-html");
      if (dict[key] !== undefined) el.innerHTML = dict[key];
    });

    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
      const key = el.getAttribute("data-i18n-ph");
      if (dict[key] !== undefined) el.setAttribute("placeholder", dict[key]);
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria");
      if (dict[key] !== undefined) el.setAttribute("aria-label", dict[key]);
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      if (dict[key] !== undefined) document.title = dict[key];
    });

    document.querySelectorAll("[data-i18n-content]").forEach((el) => {
      const key = el.getAttribute("data-i18n-content");
      if (dict[key] !== undefined) el.setAttribute("content", dict[key]);
    });

    document.documentElement.setAttribute("lang", lang === "gl" ? "gl" : lang);

    document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
      btn.setAttribute("aria-pressed", String(btn.getAttribute("data-lang-btn") === lang));
    });

    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* noop */ }

    document.dispatchEvent(new CustomEvent("latrama:lang", { detail: { lang } }));
  }

  function initSwitcher() {
    document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
      btn.addEventListener("click", () => applyLang(btn.getAttribute("data-lang-btn")));
    });
  }

  window.LaTrama = { t, applyLang, get lang() { return current; }, langs: Object.keys(I18N) };

  document.addEventListener("DOMContentLoaded", () => {
    initSwitcher();
    applyLang(detectLang());
  });
})();
